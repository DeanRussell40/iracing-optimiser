"""Writes iroptimizer/webui/demo.js: real view data from sample bundles, for previewing the page in a browser
(open index.html?demo). Run: python tools_dev/make_demo.py"""
import json, sys, tempfile
from pathlib import Path
root = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(root), str(root / "tests")]
from iroptimizer import dashboard, abtest  # noqa: E402
from test_ui import history_dir  # noqa: E402
from test_audit import sample  # noqa: E402

with tempfile.TemporaryDirectory() as d:
    v = dashboard.view(history_dir(Path(d)) / "bench", 1, None, "NEW_SIM_PC · RTX 5080")
v.update(version="demo", focus_labels=list(abtest.FOCUS_LABELS), job=None, notice="",
         backups={"available": True, "locked": True, "folder": r"C:\Users\you\Documents\iRacing",
                  "items": [{"id": "20261126_154101_original", "when": "26 Nov 2026, 3:41 PM",
                             "why": "Your settings before the app changed anything", "original": True,
                             "files": ["app.ini", "rendererDX11Monitor.ini"]}]})
js = """// Demo data for previewing the page in a browser (index.html?demo). Generated by tools_dev/make_demo.py.
(() => {
const VIEW = %s;
const AUDIT = %s;
let job = null, t0 = 0;
const sleep = ms => new Promise(r => setTimeout(r, ms));
window.DEMO_API = {
  view: async () => ({...VIEW, job}),
  set_focus: async () => ({ok: true}),
  scan_background: async () => { await sleep(1200); return {ok: true, apps: [{name: "SimHubWPF.exe", cores: 0.9}, {name: "simmixer.exe", cores: 0.35}, {name: "pythonw.exe", cores: 0.06}]}; },
  start: async (test, o) => { t0 = Date.now(); job = {title: test === "guided" ? `${o.b} vs ${o.a}` : test === "background" ? "Background apps: running vs paused" : "Measure my PC", state: "running", logs: [], eta_s: 720}; return {ok: true, title: job.title, eta_min: 12}; },
  poll: async () => { if (!job) return {job: null}; const el = (Date.now() - t0) / 1000;
    const j = {...job, elapsed_s: el * 30, progress: Math.min(.99, el * 30 / 720), next: 0,
      logs: [{t: "17:20:0" + Math.floor(el %% 10), text: "Run " + (1 + Math.floor(el / 2)) + "/11: measuring 60 s"}],
      prompt: job.title.includes("G-Sync") && el > 3 && !job.answered ? {id: "p1", title: "Set up B: G-Sync on", text: "The replay is paused. Change it, then press Done."} : null};
    if (el > 6) { job.state = "done"; job.result = {id: "demo", verdicts: ["same"], lines: ["No meaningful difference: the change didn't move 1%% lows, frame-time spikes or stutters beyond run-to-run noise.", "Repeatable: runs agree within 1.5%%."]}; Object.assign(j, {state: "done", result: job.result, progress: 1}); }
    return {job: j}; },
  answer: async () => { job.answered = true; return {ok: true}; },
  stop: async () => { job.state = "stopped"; return {ok: true}; },
  update_status: async () => ({available: false, state: "current"}), update_install: async () => ({ok: false}), open_classic: async () => ({ok: true}), open_report: async () => ({ok: true}), open_results_folder: async () => ({ok: true}),
  relaunch_admin: async () => ({ok: true}), backup_now: async () => ({ok: true}), restore: async () => ({ok: true}),
  log_js: async () => ({ok: true}), add_note: async () => ({ok: true}),
  audit: async () => { await sleep(600); return {ok: true, ...AUDIT}; },
};
})();
""" % (json.dumps(v, ensure_ascii=False, indent=1), json.dumps(sample(), ensure_ascii=False))
(root / "iroptimizer" / "webui" / "demo.js").write_text(js, encoding="utf-8")
print("ok")
